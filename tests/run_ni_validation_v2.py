#!/usr/bin/env python3
"""
run_ni_validation_v2.py -- reproducible live Network Intelligence validation.

Run as root:  sudo python3 tests/run_ni_validation_v2.py --configs A,B,C,D1,D2,F --trials 5

Design rules
  * one fresh Mininet topology + one adg-xdp daemon + one osken controller PER TRIAL
  * XDP attached to s1-eth1 (h1's switch port, ingress only) and verified before traffic
  * only processes started by this harness are ever signalled (no pkill)
  * all raw artifacts persisted under <out>/runs/<run_id>/
  * nothing is fabricated: stages with no instrumentation are reported as such

Configs
  A  benign baseline (ICMP + 1 MB HTTP transfer + small TCP exchange)
  B  SYN/connect scan of h2 ports 1-100
  C  destination diversity: h1 -> h2..h11 :80, one connection each
  D1 closed-port connection attempts (RST generated by the *responder*)
  D2 abortive close to open ports (RST generated by h1 itself)
  F  bulk transfer then idle triggers (risk-isolation probe: trust expected high)
Every run issues three PacketIn triggers from h1 (fresh destination each):
  T_a immediately after the workload, T_b +4 s idle, T_c +34 s idle.
"""
import argparse, csv, json, os, re, signal, subprocess, sys, threading, time, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "controller"))
HELPER = ROOT / "tests" / "ni_v2_helpers.py"
XDP_BIN = ROOT / "adg-xdp" / "target" / "release" / "adg-xdp"
OF_PORT = 6653
N_HOSTS = 14
SRC_IP = "10.0.0.1"
DEST_HOSTS = list(range(2, 12))          # h2..h11 workload destinations
TRIGGERS = {"T_a": 12, "T_b": 13, "T_c": 14}


def mac(n):
    return "00:00:00:00:00:%02x" % n


def now():
    return time.time()


class Tailer(threading.Thread):
    """Tails files, stamping each new line with wall-clock arrival time."""
    def __init__(self, paths):
        super().__init__(daemon=True)
        self.paths = paths                      # name -> Path
        self.lines = {k: [] for k in paths}     # name -> [(t, line)]
        self.pos = {k: 0 for k in paths}
        self.buf = {k: "" for k in paths}
        self.stop_ev = threading.Event()

    def run(self):
        while not self.stop_ev.is_set():
            self.poll()
            time.sleep(0.05)
        self.poll()

    def poll(self):
        for k, p in self.paths.items():
            try:
                with open(p, "rb") as f:
                    f.seek(self.pos[k]); data = f.read()
                    self.pos[k] += len(data)
            except FileNotFoundError:
                continue
            if not data:
                continue
            t = now()
            txt = self.buf[k] + data.decode("utf-8", "replace")
            parts = txt.split("\n")
            self.buf[k] = parts.pop()
            for ln in parts:
                self.lines[k].append((t, ln))


class MapPoller(threading.Thread):
    """Reads HOST_TRUST / HOST_RISK for SRC_IP through the controller's own stores."""
    def __init__(self, interval=0.25):
        super().__init__(daemon=True)
        from trust import TrustStore
        from risk import RiskStore
        self.ts, self.rs = TrustStore(), RiskStore()
        self.rows = []
        self.interval = interval
        self.stop_ev = threading.Event()
        self.map_ok = self.ts.map_fd is not None and self.rs.map_fd is not None

    def read(self):
        return self.ts.get(SRC_IP), self.rs.get(SRC_IP)

    def run(self):
        while not self.stop_ev.is_set():
            t = now(); tr, rk = self.read()
            self.rows.append((t, tr, rk))
            time.sleep(self.interval)


def sh(cmd, **kw):
    return subprocess.run(cmd, shell=isinstance(cmd, str), capture_output=True, text=True, **kw)


def wait_for(pred, timeout, step=0.1):
    t0 = now()
    while now() - t0 < timeout:
        if pred():
            return True
        time.sleep(step)
    return False


def file_has(path, needle):
    try:
        return needle in Path(path).read_text(errors="replace")
    except FileNotFoundError:
        return False


