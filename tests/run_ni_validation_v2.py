def parse_daemon(lines):
    """Parse adg-xdp telemetry cycles into per-host rows. lines = [(t, str)]"""
    rows, cur_t, cur = [], None, {}
    summary = {}
    for t, ln in lines:
        m = re.match(r"^(\d+\.\d+\.\d+\.\d+)\s+\|.*\|\s*(\d+)\s*\|\s*(-?\d+)\s*\|\s*(-?\d+)\s*\|\s*(\w+)\s*$", ln)
        if m:
            cur = {"t": t, "host": m.group(1), "trust": int(m.group(2)), "level": m.group(5)}
            rows.append(cur); continue
        if not cur:
            continue
        m = re.search(r"Observed:\s+flows=(\d+), unique_dst_ips=(\d+), unique_dst_ports=(\d+), rst_count=(\d+)", ln)
        if m:
            cur.update(flows=int(m[1]), dst_ips=int(m[2]), dst_ports=int(m[3]), rst=int(m[4])); continue
        m = re.search(r"Rates:\s+([\d.]+) Bps, ([\d.]+) Pps", ln)
        if m:
            cur.update(bps=float(m[1]), pps=float(m[2])); continue
        m = re.search(r"Graph:\s+weighted_out_degree=(-?\d+), neighbors=(\d+), component_size=(\d+), bfs_reach=(\d+), dfs_depth=(\d+)", ln)
        if m:
            cur.update(wod=int(m[1]), neighbors=int(m[2]), comp=int(m[3]), bfs=int(m[4]), dfs=int(m[5])); continue
        m = re.search(r"Risk:\s+total=(-?[\d.]+), dest=(-?[\d.]+), port_scan=(-?[\d.]+), conn_fail=(-?[\d.]+), centrality=(-?[\d.]+)", ln)
        if m:
            cur.update(risk_total=float(m[1]), dest=float(m[2]), port=float(m[3]), rstr=float(m[4]), cent=float(m[5])); continue
        m = re.search(r"HOST_TRUST=(\d+), HOST_RISK=(\d+)", ln)
        if m:
            cur.update(host_risk=int(m[2]), t=t); continue
        m = re.search(r"Graph Summary: nodes=(\d+), edges=(\d+), components=(\d+), expired_edges=(\d+), flow_table_size=(\d+), total_events=(\d+)", ln)
        if m:
            for r in rows[::-1]:
                if r.get("t") is not None and "gs_nodes" not in r and r["t"] >= cur["t"] - 0.5:
                    pass
            summary_row = dict(t=t, nodes=int(m[1]), edges=int(m[2]), components=int(m[3]),
                               expired=int(m[4]), ft=int(m[5]), events=int(m[6]))
            summary.setdefault("rows", []).append(summary_row)
    return rows, summary.get("rows", [])


def parse_controller(lines):
    """Return decision records [{t, src_mac, dst_mac, in_port, ip, trust, risk, decision, priority}]"""
    recs, pend, cur = [], None, None
    for t, ln in lines:
        m = re.search(r"PACKET_IN Switch=(\S+) SRC=(\S+) DST=(\S+) IN=(\S+)", ln)
        if m:
            pend = dict(t_pktin=t, src_mac=m[2], dst_mac=m[3], in_port=m[4]); cur = None; continue
        if "Not an IPv4 packet" in ln and pend:
            recs.append(dict(pend, ip=None, trust=None, risk=None, decision="ALLOW(non-IPv4)", priority=None, t=t)); pend = None; continue
        m = re.search(r"Host : (\S+)", ln)
        if m and pend is not None:
            cur = dict(pend, ip=m[1]); continue
        if cur is not None:
            m = re.search(r"Trust : (\S+)", ln)
            if m: cur["trust"] = int(m[1]); continue
            m = re.search(r"Risk : (\S+)", ln)
            if m: cur["risk"] = int(m[1]); continue
            m = re.search(r"Decision : (\S+)", ln)
            if m: cur["decision"] = m[1]; continue
            m = re.search(r"Priority : (\S+)", ln)
            if m:
                cur["priority"] = int(m[1]); cur["t"] = t; recs.append(cur); cur = None; pend = None
    return recs


def pcap_count(pcap, flt):
    r = sh(["tcpdump", "-nn", "-q", "-r", str(pcap), flt])
    return len([l for l in r.stdout.splitlines() if l.strip()])


