def analyse(d, meta, tail, poller):
    """Derive per-run summary + sub-rows from persisted artifacts."""
    out = {"run_id": meta["run_id"], "cfg": meta["cfg"], "trial": meta["trial"], "status": meta["status"],
           "reason": meta.get("failure_reason", ""), "artifact": str(d)}
    if meta["status"] != "OK" or not tail:
        return out, [], [], []
    ev = meta["events"]
    drows, gsum = parse_daemon(tail.lines["daemon"])
    h1 = [r for r in drows if r["host"] == SRC_IP and "risk_total" in r]
    recs = parse_controller(tail.lines["ctrl"])
    t_ws, t_we = ev["workload_start"], ev["workload_end"]

    during = [r for r in h1 if t_ws - 0.1 <= r["t"] <= t_we + 2.5]
    pk = max(during, key=lambda r: r["host_risk"]) if during else None
    out.update(
        pre_trust=meta.get("pre_trust"), pre_risk=meta.get("pre_risk"),
        workload=json.dumps(meta.get("workload")),
        min_trust_during=min([r["trust"] for r in during], default=""),
        peak_host_risk=pk["host_risk"] if pk else "",
        peak_flows=pk["flows"] if pk else "", peak_dst_ips=pk["dst_ips"] if pk else "",
        peak_dst_ports=pk["dst_ports"] if pk else "", peak_rst=pk["rst"] if pk else "",
        peak_dest=pk["dest"] if pk else "", peak_port=pk["port"] if pk else "",
        peak_rstr=pk["rstr"] if pk else "", peak_cent=pk["cent"] if pk else "",
        peak_risk_total=pk["risk_total"] if pk else "",
        peak_wod=pk["wod"] if pk else "", peak_pps=pk["pps"] if pk else "",
        max_comp=max([r["comp"] for r in h1], default=""),
        max_bfs=max([r["bfs"] for r in h1], default=""),
        max_dfs=max([r["dfs"] for r in h1], default=""),
        max_neighbors=max([r["neighbors"] for r in h1], default=""),
        daemon_cycles=len(h1),
        xdp_events=max([g["events"] for g in gsum], default=0),
        max_expired_edges=max([g["expired"] for g in gsum], default=0),
        final_ft=gsum[-1]["ft"] if gsum else "", final_edges=gsum[-1]["edges"] if gsum else "",
    )
    pc = d / "s1-eth1.pcap"
    out["pcap_h1_syn_fin_rst_pkts"] = pcap_count(pc, "ip src 10.0.0.1 and tcp and (tcp[tcpflags] & (tcp-syn|tcp-fin|tcp-rst) != 0)")
    out["pcap_h1_syn_pkts"] = pcap_count(pc, "ip src 10.0.0.1 and tcp and (tcp[tcpflags] & tcp-syn != 0)")
    out["pcap_h1_rst_pkts"] = pcap_count(pc, "ip src 10.0.0.1 and tcp and (tcp[tcpflags] & tcp-rst != 0)")
    out["pcap_other_rst_pkts"] = pcap_count(pc, "not ip src 10.0.0.1 and tcp and (tcp[tcpflags] & tcp-rst != 0)")
    out["xdp_vs_pcap_event_delta"] = out["xdp_events"] - out["pcap_h1_syn_fin_rst_pkts"] if out["xdp_events"] != "" else ""

    # policy decisions correlated with triggers (src ip + dst MAC + time window)
    e2e = []
    for label, tr in meta["triggers"].items():
        matches = [r for r in recs if r.get("ip") == SRC_IP and r["dst_mac"] == tr["dst_mac"]
                   and tr["t0"] - 0.05 <= r["t"] <= tr["t1"] + 1.0]
        first = matches[0] if matches else None
        def has(fn, pri):
            try:
                return bool(re.search(r"priority=%d,ip,nw_src=10\.0\.0\.1 " % pri, (d / fn).read_text()))
            except FileNotFoundError:
                return ""
        pre_f, post_f = "ovs_flows_%s_pre.txt" % label, "ovs_flows_%s_post.txt" % label
        e2e.append(dict(run_id=meta["run_id"], cfg=meta["cfg"], trial=meta["trial"], trigger=label,
                        t_since_workload_end_s=round(tr["t0"] - t_we, 2),
                        harness_pre_trust=tr["pre_trust"], harness_pre_risk=tr["pre_risk"],
                        reply=tr["reply"], decision_found=bool(first),
                        ctrl_trust=first["trust"] if first else "", ctrl_risk=first["risk"] if first else "",
                        decision=first["decision"] if first else "", priority=first["priority"] if first else "",
                        n_policy_records=len(matches),
                        prio120_ipsrc_before=has(pre_f, 120), prio120_ipsrc_after=has(post_f, 120),
                        prio200_ipsrc_before=has(pre_f, 200), prio200_ipsrc_after=has(post_f, 200),
                        t_pktin_minus_trigger_ms=round((first["t_pktin"] - tr["t0"]) * 1e3, 1) if first else ""))
    # trigger isolation classification
    for r in e2e:
        if r["decision_found"] and r["ctrl_trust"] != "" and r["ctrl_risk"] != "":
            trust_driven = r["ctrl_trust"] < 70
            risk_driven = (r["ctrl_risk"] >= 80 and r["ctrl_trust"] >= 70 and r["decision"] == "MIRROR")
            r["classification"] = "RISK_DRIVEN" if risk_driven else ("TRUST_DRIVEN" if trust_driven and r["decision"] != "ALLOW" else "NEITHER/ALLOW")
        else:
            r["classification"] = "NO_DECISION_CAPTURED"

    # flows after
    after = (d / "ovs_flows_after.txt").read_text()
    out["after_has_prio120_ipsrc_h1"] = bool(re.search(r"priority=120.*nw_src=10\.0\.0\.1", after))
    out["after_has_prio200_ipsrc_h1"] = bool(re.search(r"priority=200.*nw_src=10\.0\.0\.1", after))
    # recovery series
    rec = []
    for r in h1:
        rec.append(dict(run_id=meta["run_id"], cfg=meta["cfg"], trial=meta["trial"],
                        t_rel_workload_end_s=round(r["t"] - t_we, 2), trust=r["trust"], host_risk=r["host_risk"],
                        flows=r["flows"], dst_ports=r["dst_ports"], rst=r["rst"], pps=r["pps"], wod=r["wod"],
                        risk_total=r["risk_total"], dest=r["dest"], port=r["port"], rstr=r["rstr"], cent=r["cent"]))
    # post-workload recovery summary
    post = [r for r in h1 if r["t"] > t_we + 2.5]
    out["post_first_risk"] = post[0]["host_risk"] if post else ""
    out["post_risks_head"] = json.dumps([p["host_risk"] for p in post[:8]])
    late = [r for r in h1 if r["t"] >= t_we + 33]
    out["late_risk"] = late[-1]["host_risk"] if late else ""
    graph = [dict(run_id=meta["run_id"], cfg=meta["cfg"], trial=meta["trial"],
                  t_rel_workload_end_s=round(g["t"] - t_we, 2), nodes=g["nodes"], edges=g["edges"],
                  components=g["components"], expired_edges=g["expired"], flow_table_size=g["ft"],
                  total_events=g["events"]) for g in gsum]
    return out, e2e, rec, graph


def write_csv(path, rows):
    if not rows:
        return
    keys = []
    for r in rows:
        for k in r:
            if k not in keys: keys.append(k)
    new = not path.exists()
    with open(path, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        if new: w.writeheader()
        w.writerows(rows)


