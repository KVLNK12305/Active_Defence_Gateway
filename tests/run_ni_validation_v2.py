def run_trial(cfg, trial, base, validation=False):
    from mininet.net import Mininet
    from mininet.node import OVSSwitch, RemoteController

    run_id = "%s_t%d_%s" % (cfg, trial, datetime.datetime.now().strftime("%Y%m%dT%H%M%S"))
    d = base / "runs" / run_id
    d.mkdir(parents=True)
    meta = dict(run_id=run_id, cfg=cfg, trial=trial, validation=validation,
                start_wall=datetime.datetime.now().isoformat(), status="RUNNING", notes=[])
    procs, net, tail, poller = [], None, None, None
    daemon_log, ctrl_log = d / "adg_xdp.log", d / "controller.log"
    ovsmon_log, pcap = d / "ovs_monitor.log", d / "s1-eth1.pcap"
    www = d / "www"; www.mkdir()
    (www / "big.bin").write_bytes(b"\0" * (1024 * 1024))
    ev = {}   # event timeline  name -> wall time

    def spawn(cmd, log, **kw):
        f = open(log, "wb")
        p = subprocess.Popen(cmd, stdout=f, stderr=subprocess.STDOUT, cwd=str(ROOT), **kw)
        procs.append((p, f)); return p

    try:
        if sh("ovs-vsctl br-exists s1").returncode == 0:
            raise RuntimeError("bridge s1 already exists before trial; refusing to touch it")
        if sh("ss -ltn 'sport = :%d'" % OF_PORT).stdout.count("LISTEN"):
            raise RuntimeError("port %d already in use" % OF_PORT)

        net = Mininet(controller=None, switch=OVSSwitch, autoSetMacs=True, build=False)
        net.addController("c0", controller=RemoteController, ip="127.0.0.1", port=OF_PORT)
        s1 = net.addSwitch("s1", protocols="OpenFlow13")
        hosts = {}
        for i in range(1, N_HOSTS + 1):
            h = net.addHost("h%d" % i, ip="10.0.0.%d/8" % i)
            net.addLink(h, s1); hosts[i] = h
        net.start()
        ev["net_started"] = now()

        # ---- XDP daemon on s1-eth1 -------------------------------------------------
        sh("ip link set s1-eth1 up")
        spawn(["tcpdump", "-i", "s1-eth1", "-nn", "-U", "-w", str(pcap)], d / "tcpdump.log")
        denv = dict(os.environ, RUST_LOG="info")
        dp = spawn([str(XDP_BIN), "--iface", "s1-eth1"], daemon_log, env=denv)
        ok = wait_for(lambda: file_has(daemon_log, "Attached XDP program") and Path("/sys/fs/bpf/HOST_RISK").exists(), 40)
        if not ok or dp.poll() is not None:
            raise RuntimeError("adg-xdp did not become ready (see adg_xdp.log)")
        xdp_info = sh("ip -d link show s1-eth1").stdout
        (d / "xdp_link.txt").write_text(xdp_info)
        if "xdp" not in xdp_info:
            raise RuntimeError("XDP program not visible on s1-eth1")
        ev["xdp_attached"] = now()

        # ---- controller -------------------------------------------------------------
        cenv = {k: v for k, v in os.environ.items() if k != "ADG_MOCK_TRUST"}
        cenv["ADG_CONTROLLER_ID"] = "C1"
        cenv.pop("ADG_DISABLE_DEDUP", None)
        cp = spawn(["osken-manager", "controller/adg_controller.py", "--ofp-tcp-listen-port", str(OF_PORT)], ctrl_log, env=cenv)
        ok = wait_for(lambda: file_has(ctrl_log, "Requested EQUAL role"), 60)
        if not ok or cp.poll() is not None:
            raise RuntimeError("controller/switch handshake not observed (see controller.log)")
        wait_for(lambda: "priority=0" in sh("ovs-ofctl -O OpenFlow13 dump-flows s1").stdout, 10)
        ev["controller_ready"] = now()

        # NOTE: OF1.3-only bridge rejects the NXST flow-monitor (OFPBRC_BAD_VERSION), so flow-table
        # evidence is taken as dump-flows snapshots immediately before/after each trigger instead.

        tail = Tailer({"daemon": daemon_log, "ctrl": ctrl_log, "ovsmon": ovsmon_log}); tail.start()
        poller = MapPoller(); poller.start()
        meta["map_ok"] = poller.map_ok
        if not poller.map_ok:
            meta["notes"].append("HOST_TRUST/HOST_RISK not openable by harness at start")

        # ---- listeners -----------------------------------------------------------------
        ports = "80,8001-8020"
        for i in DEST_HOSTS:
            procs_p = hosts[i].popen(["python3", str(HELPER), "listen", "--ip", "10.0.0.%d" % i, "--ports", ports],
                                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            procs.append((procs_p, None))
        hp = hosts[2].popen(["python3", "-m", "http.server", "8080", "--bind", "10.0.0.2", "--directory", str(www)],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        procs.append((hp, None))
        time.sleep(1.0)

        sh("ovs-ofctl -O OpenFlow13 dump-flows s1 > %s" % (d / "ovs_flows_before.txt"))
        time.sleep(4.0)                                           # warm-up (explicit)
        meta["pre_trust"], meta["pre_risk"] = poller.read()
        h1 = hosts[1]

        # ---- workload -----------------------------------------------------------------
        def jrun(cmd):
            out = h1.cmd("%s; echo __EXIT=$?" % cmd)
            m = re.search(r"__EXIT=(\d+)", out)
            body = out.split("__EXIT=")[0].strip()
            try:
                j = json.loads(body.splitlines()[-1]) if body else {}
            except Exception:
                j = {"raw": body}
            j["exit"] = int(m.group(1)) if m else None
            return j

        ev["workload_start"] = now()
        wl = {}
        if cfg == "A":
            out = h1.cmd("ping -c 5 -i 0.2 10.0.0.2")
            wl["ping"] = {"received": int(re.search(r"(\d+) received", out).group(1)) if "received" in out else 0, "sent": 5}
            wl["bulk"] = jrun("python3 %s bulk --target 10.0.0.2 --port 8080" % HELPER)
            wl["tcp_small"] = jrun("python3 %s fanout --targets 10.0.0.3 --port 80 --payload-packets 20" % HELPER)
        elif cfg == "B":
            wl["scan"] = jrun("python3 %s scan --target 10.0.0.2 --ports 1-100 --timeout 0.5" % HELPER)
        elif cfg == "C":
            wl["fanout"] = jrun("python3 %s fanout --targets %s --port 80 --payload-packets 30" %
                                (HELPER, ",".join("10.0.0.%d" % i for i in DEST_HOSTS)))
        elif cfg == "D1":
            wl["closed_ports"] = jrun("python3 %s scan --target 10.0.0.2 --ports 9001-9020 --timeout 0.5" % HELPER)
        elif cfg == "D2":
            wl["abort"] = jrun("python3 %s abort --target 10.0.0.3 --ports 8001-8020" % HELPER)
        elif cfg == "F":
            wl["bulk"] = jrun("python3 %s bulk --target 10.0.0.2 --port 8080" % HELPER)
        else:
            raise RuntimeError("unknown cfg " + cfg)
        ev["workload_end"] = now()
        meta["workload"] = wl

        # ---- triggers ----------------------------------------------------------------
        trig = {}

        def do_trigger(label):
            n = TRIGGERS[label]
            pre = poller.read()
            sh("ovs-ofctl -O OpenFlow13 dump-flows s1 > %s" % (d / ("ovs_flows_%s_pre.txt" % label)))
            t0 = now()
            out = h1.cmd("ping -c 1 -W 2 10.0.0.%d" % n)
            t1 = now()
            time.sleep(0.3)
            sh("ovs-ofctl -O OpenFlow13 dump-flows s1 > %s" % (d / ("ovs_flows_%s_post.txt" % label)))
            trig[label] = dict(dst_ip="10.0.0.%d" % n, dst_mac=mac(n), t0=t0, t1=t1,
                               reply=("1 received" in out), pre_trust=pre[0], pre_risk=pre[1])

        do_trigger("T_a")
        time.sleep(4.0)
        do_trigger("T_b")
        wait_for(lambda: now() >= ev["workload_end"] + 34.0, 60, 0.2)
        do_trigger("T_c")
        time.sleep(3.0)
        ev["end"] = now()
        meta["triggers"] = trig

        sh("ovs-ofctl -O OpenFlow13 dump-flows s1 > %s" % (d / "ovs_flows_after.txt"))
        meta["status"] = "OK"
    except Exception as e:                                       # noqa
        meta["status"] = "FAILED"
        meta["failure_reason"] = repr(e)
    finally:
        if poller: poller.stop_ev.set()
        # stop only what we started
        for p, f in procs[::-1]:
            try:
                if p.poll() is None:
                    p.send_signal(signal.SIGINT)
            except Exception:
                pass
        time.sleep(1.0)
        for p, f in procs[::-1]:
            try:
                if p.poll() is None:
                    p.terminate()
                    try: p.wait(3)
                    except Exception: p.kill()
            except Exception:
                pass
            if f: f.close()
        if tail:
            tail.stop_ev.set(); tail.join(2)
        if net:
            try: net.stop()
            except Exception: pass

    # ---- persist raw + derived ---------------------------------------------------------
    meta["events"] = ev
    meta["end_wall"] = datetime.datetime.now().isoformat()
    if tail:
        for k, v in tail.lines.items():
            with open(d / ("stamped_%s.log" % k), "w") as f:
                for t, ln in v:
                    f.write("%.3f\t%s\n" % (t, ln))
    if poller:
        with open(d / "maps_poll.csv", "w", newline="") as f:
            w = csv.writer(f); w.writerow(["t_wall_s", "host_trust", "host_risk"])
            w.writerows(poller.rows)
    (d / "meta.json").write_text(json.dumps(meta, indent=1, default=str))
    return d, meta, tail, poller


